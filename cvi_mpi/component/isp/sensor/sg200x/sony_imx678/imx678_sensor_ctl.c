static void delay_ms(int ms)
{
	usleep(ms * 1000);
}

int imx678_i2c_init(VI_PIPE ViPipe)
{
	char acDevFile[16] = {0};
	CVI_U8 u8DevNum;
	int ret;

	if (g_fd[ViPipe] >= 0)
		return CVI_SUCCESS;

	u8DevNum = g_aunImx678_BusInfo[ViPipe].s8I2cDev;
	snprintf(acDevFile, sizeof(acDevFile), "/dev/i2c-%u", u8DevNum);
	g_fd[ViPipe] = open(acDevFile, O_RDWR, 0600);
	if (g_fd[ViPipe] < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "Open /dev/i2c-%u error!\n", u8DevNum);
		return CVI_FAILURE;
	}

	ret = ioctl(g_fd[ViPipe], I2C_SLAVE_FORCE, imx678_i2c_addr);
	if (ret < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "I2C_SLAVE_FORCE error!\n");
		close(g_fd[ViPipe]);
		g_fd[ViPipe] = -1;
		return ret;
	}

	return CVI_SUCCESS;
}

int imx678_i2c_exit(VI_PIPE ViPipe)
{
	if (g_fd[ViPipe] >= 0) {
		close(g_fd[ViPipe]);
		g_fd[ViPipe] = -1;
		return CVI_SUCCESS;
	}
	return CVI_FAILURE;
}

int imx678_read_register(VI_PIPE ViPipe, int addr)
{
	int ret, data;
	CVI_U8 buf[8];
	CVI_U8 idx = 0;

	if (g_fd[ViPipe] < 0)
		return CVI_FAILURE;

	if (imx678_addr_byte == 2)
		buf[idx++] = (addr >> 8) & 0xff;
	buf[idx++] = addr & 0xff;

	ret = write(g_fd[ViPipe], buf, imx678_addr_byte);
	if (ret < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "I2C_WRITE error! addr=0x%x errno=%d(%s)\n",
			      addr, errno, strerror(errno));
		return ret;
	}

	buf[0] = 0;
	buf[1] = 0;
	ret = read(g_fd[ViPipe], buf, imx678_data_byte);
	if (ret < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "I2C_READ error!\n");
		return ret;
	}

	data = buf[0];
	syslog(LOG_DEBUG, "i2c r 0x%x = 0x%x\n", addr, data);
	return data;
}

int imx678_write_register(VI_PIPE ViPipe, int addr, int data)
{
	CVI_U8 idx = 0;
	int ret;
	CVI_U8 buf[8];

	if (g_fd[ViPipe] < 0)
		return CVI_SUCCESS;

	buf[idx++] = (addr >> 8) & 0xff;
	buf[idx++] = addr & 0xff;
	buf[idx++] = data & 0xff;

	ret = write(g_fd[ViPipe], buf, imx678_addr_byte + imx678_data_byte);
	if (ret < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "I2C_WRITE error! addr=0x%x errno=%d(%s)\n",
			      addr, errno, strerror(errno));
		return CVI_FAILURE;
	}
	syslog(LOG_DEBUG, "i2c w 0x%x 0x%x\n", addr, data);
	return CVI_SUCCESS;
}

static void imx678_write_table(VI_PIPE ViPipe, const struct imx678_regval *regs)
{
	int i;

	for (i = 0; regs[i].addr != IMX678_REG_NULL; i++) {
		if (regs[i].addr == IMX678_REG_DELAY)
			delay_ms(regs[i].data);
		else
			imx678_write_register(ViPipe, regs[i].addr, regs[i].data);
	}
}

void imx678_standby(VI_PIPE ViPipe)
{
	imx678_write_register(ViPipe, 0x3000, 0x01); /* STANDBY */
	imx678_write_register(ViPipe, 0x3002, 0x01); /* XMSTA */
}

void imx678_restart(VI_PIPE ViPipe)
{
	imx678_write_register(ViPipe, 0x3000, 0x00); /* exit standby */
	delay_ms(80);
	imx678_write_register(ViPipe, 0x3002, 0x00); /* master mode start */
}

void imx678_mirror_flip(VI_PIPE ViPipe, ISP_SNS_MIRRORFLIP_TYPE_E eSnsMirrorFlip)
{
	CVI_U8 flip = imx678_read_register(ViPipe, 0x3021) & ~0x1;
	CVI_U8 mirror = imx678_read_register(ViPipe, 0x3020) & ~0x1;

	switch (eSnsMirrorFlip) {
	case ISP_SNS_MIRROR:
		mirror |= 0x1;
		break;
	case ISP_SNS_FLIP:
		flip |= 0x1;
		break;
	case ISP_SNS_MIRROR_FLIP:
		mirror |= 0x1;
		flip |= 0x1;
		break;
	default:
		break;
	}

	imx678_write_register(ViPipe, 0x3020, mirror);
	imx678_write_register(ViPipe, 0x3021, flip);
}

int imx678_probe(VI_PIPE ViPipe)
{
	int id;
	int retry;

	if (imx678_i2c_init(ViPipe) != CVI_SUCCESS)
		return CVI_FAILURE;

	/* Allow sensor to wake from reset before the first ID read. */
	delay_ms(10);

	for (retry = 0; retry < 5; retry++) {
		if (retry > 0)
			delay_ms(10);

		id = imx678_read_register(ViPipe, IMX678_CHIP_ID_ADDR);
		if (id >= 0 && (id & 0xff) == IMX678_CHIP_ID)
			return CVI_SUCCESS;
	}

	if (id < 0) {
		CVI_TRACE_SNS(CVI_DBG_ERR, "read sensor id error\n");
		imx678_i2c_exit(ViPipe);
		return id;
	}

	CVI_TRACE_SNS(CVI_DBG_ERR, "Sensor ID Mismatch! read 0x%x, expect 0x%x\n", id, IMX678_CHIP_ID);
	imx678_i2c_exit(ViPipe);
	return CVI_FAILURE;
}

/* Center crop 2880x1620 from full 3856x2180 all-pixel readout (SG2000 5MP limit) */
static void imx678_apply_5m_crop(VI_PIPE ViPipe)
{
	imx678_write_register(ViPipe, 0x303C, 0xE8); /* PIX_HST = 488 */
	imx678_write_register(ViPipe, 0x303D, 0x01);
	imx678_write_register(ViPipe, 0x303E, 0x40); /* PIX_HWIDTH = 2880 */
	imx678_write_register(ViPipe, 0x303F, 0x0B);
	imx678_write_register(ViPipe, 0x3044, 0x18); /* PIX_VST = 280 */
	imx678_write_register(ViPipe, 0x3045, 0x01);
	imx678_write_register(ViPipe, 0x3046, 0x54); /* PIX_VWIDTH = 1620 */
	imx678_write_register(ViPipe, 0x3047, 0x06);
}

/* Center crop 1920x1080 from full 3856x2180 all-pixel readout */
static void imx678_apply_1080p_crop(VI_PIPE ViPipe)
{
	imx678_write_register(ViPipe, 0x303C, 0xC8); /* PIX_HST = 968 */
	imx678_write_register(ViPipe, 0x303D, 0x03);
	imx678_write_register(ViPipe, 0x303E, 0x80); /* PIX_HWIDTH = 1920 */
	imx678_write_register(ViPipe, 0x303F, 0x07);
	imx678_write_register(ViPipe, 0x3044, 0x26); /* PIX_VST = 550 */
	imx678_write_register(ViPipe, 0x3045, 0x02);
	imx678_write_register(ViPipe, 0x3046, 0x38); /* PIX_VWIDTH = 1080 */
	imx678_write_register(ViPipe, 0x3047, 0x04);
}

/*
 * 2x2 hardware binning -> MIPI ~1920x1080, full FOV.
 * Logic from Linux upstream imx678_program_window():
 *   ADDMODE=1, WINMODE=4 when crop != full active (3856x2180),
 *   PIX window = 3840x2160 centered, ADBIT=0 (10-bit AD for binning).
 */
static void imx678_apply_1080p_binning(VI_PIPE ViPipe)
{
	imx678_write_register(ViPipe, 0x301B, 0x01); /* ADDMODE = 2x2 binning */
	imx678_write_register(ViPipe, 0x3018, 0x04); /* WINMODE = window crop */
	imx678_write_register(ViPipe, 0x303C, 0x08); /* PIX_HST = 8 */
	imx678_write_register(ViPipe, 0x303D, 0x00);
	imx678_write_register(ViPipe, 0x303E, 0x00); /* PIX_HWIDTH = 3840 */
	imx678_write_register(ViPipe, 0x303F, 0x0F);
	imx678_write_register(ViPipe, 0x3044, 0x08); /* PIX_VST = 8 */
	imx678_write_register(ViPipe, 0x3045, 0x00);
	imx678_write_register(ViPipe, 0x3046, 0x70); /* PIX_VWIDTH = 2160 */
	imx678_write_register(ViPipe, 0x3047, 0x08);
	imx678_write_register(ViPipe, 0x3022, 0x00); /* ADBIT = 10-bit */
	imx678_write_register(ViPipe, 0x3023, 0x00); /* MDBIT = 10-bit MIPI */
	imx678_write_register(ViPipe, 0x301C, 0x00); /* THIN_V_EN = off */
}

/* Linux upstream stream-on for binning: STANDBY clear -> delay -> XMSTA start */
static void imx678_stream_on_binning(VI_PIPE ViPipe)
{
	imx678_write_register(ViPipe, 0x3000, 0x00);
	delay_ms(25);
	imx678_write_register(ViPipe, 0x3002, 0x00);
}

/* Proven CVITEK stream-on used by 4K/crop modes on SG2000 */
static void imx678_stream_on_cvitek(VI_PIPE ViPipe)
{
	imx678_write_register(ViPipe, 0x3002, 0x01);
	imx678_write_register(ViPipe, 0x3000, 0x00);
	delay_ms(80);
	imx678_write_register(ViPipe, 0x3002, 0x00);
}

void imx678_init(VI_PIPE ViPipe)
{
	CVI_U8 u8ImgMode;
	int standby, xmsta, hmax, vmax, pix_w, pix_h;
	int addmode, adbit, winmode;

	delay_ms(1);
	if (imx678_i2c_init(ViPipe) != CVI_SUCCESS)
		return;

	u8ImgMode = g_pastImx678[ViPipe]->u8ImgMode;

	imx678_write_register(ViPipe, 0x3000, 0x01);
	imx678_write_register(ViPipe, 0x3002, 0x01);
	imx678_write_table(ViPipe, imx678_linear_12bit_3840x2160_regs);
	if (u8ImgMode == IMX678_MODE_8M30)
		imx678_apply_5m_crop(ViPipe);
	else if (u8ImgMode == IMX678_MODE_2M30)
		imx678_apply_1080p_crop(ViPipe);
	else if (u8ImgMode == IMX678_MODE_2M30_BIN)
		imx678_apply_1080p_binning(ViPipe);

	if (u8ImgMode == IMX678_MODE_2M30_BIN)
		imx678_stream_on_binning(ViPipe);
	else
		imx678_stream_on_cvitek(ViPipe);

	standby = imx678_read_register(ViPipe, 0x3000);
	xmsta = imx678_read_register(ViPipe, 0x3002);
	hmax = imx678_read_register(ViPipe, 0x302C) | (imx678_read_register(ViPipe, 0x302D) << 8);
	vmax = imx678_read_register(ViPipe, 0x3028) | (imx678_read_register(ViPipe, 0x3029) << 8);
	pix_w = imx678_read_register(ViPipe, 0x303E) | (imx678_read_register(ViPipe, 0x303F) << 8);
	pix_h = imx678_read_register(ViPipe, 0x3046) | (imx678_read_register(ViPipe, 0x3047) << 8);
	addmode = imx678_read_register(ViPipe, 0x301B);
	adbit = imx678_read_register(ViPipe, 0x3022);
	winmode = imx678_read_register(ViPipe, 0x3018);

	if (u8ImgMode == IMX678_MODE_2M30_BIN)
		printf("ViPipe:%d,===IMX678 1080P30fps 10bit LINE(bin) Init OK!=== "
		       "STBY=%#x XMSTA=%#x HMAX=%d VMAX=%d PIX=%dx%d "
		       "ADDMODE=%#x WINMODE=%#x ADBIT=%#x\n",
		       ViPipe, standby & 0xff, xmsta & 0xff, hmax, vmax, pix_w, pix_h,
		       addmode & 0xff, winmode & 0xff, adbit & 0xff);
	else if (u8ImgMode == IMX678_MODE_2M30)
		printf("ViPipe:%d,===IMX678 1080P30fps 12bit LINE(crop) Init OK!=== "
		       "STBY=%#x XMSTA=%#x HMAX=%d VMAX=%d PIX=%dx%d\n",
		       ViPipe, standby & 0xff, xmsta & 0xff, hmax, vmax, pix_w, pix_h);
	else
		printf("ViPipe:%d,===IMX678 2880x1620 30fps 12bit LINE(crop) Init OK!=== "
		       "STBY=%#x XMSTA=%#x HMAX=%d VMAX=%d PIX=%dx%d\n",
		       ViPipe, standby & 0xff, xmsta & 0xff, hmax, vmax, pix_w, pix_h);
	g_pastImx678[ViPipe]->bInit = CVI_TRUE;
}

void imx678_exit(VI_PIPE ViPipe)
{
	imx678_standby(ViPipe);
	imx678_i2c_exit(ViPipe);
}
